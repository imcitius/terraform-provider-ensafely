// Resource schema.

func (f checkField) resourceAttribute() schema.Attribute {
	optional := !f.required
	switch f.kind {
	case kindInt:
		return schema.Int64Attribute{Required: f.required, Optional: optional, MarkdownDescription: f.desc,
			Validators: []validator.Int64{int64Range{min: f.minInt, max: f.maxInt}}}
	case kindBool:
		// The API stores false as "unset"; a false default keeps the mapping
		// lossless and avoids a diff for an explicit false.
		return schema.BoolAttribute{Optional: true, Computed: true, Default: booldefault.StaticBool(false), MarkdownDescription: f.desc}
	case kindIntSet:
		return schema.SetAttribute{ElementType: types.Int64Type, Required: f.required, Optional: optional, MarkdownDescription: f.desc,
			Validators: []validator.Set{setCheck{elemMin: f.minInt, elemMax: f.maxInt}}}
	case kindStringSet:
		return schema.SetAttribute{ElementType: types.StringType, Required: f.required, Optional: optional, MarkdownDescription: f.desc,
			Validators: []validator.Set{setCheck{}}}
	default:
		return schema.StringAttribute{Required: f.required, Optional: optional, MarkdownDescription: f.desc,
			Validators: []validator.String{stringCheck{duration: f.duration, oneOf: f.oneOf}}}
	}
}

func (t checkType) resourceBlock() schema.SingleNestedBlock {
	attrs := make(map[string]schema.Attribute, len(t.fields)+2*len(t.secrets))
	for _, f := range t.fields {
		// Terraform rejects a required attribute in an absent single nested
		// block, so required fields of a type block are optional in the
		// schema and enforced by validateCheckConfig.
		if f.required {
			f.required = false
			if !f.fromConnection {
				f.desc = "Required. " + f.desc
			}
		}
		attrs[f.name] = f.resourceAttribute()
	}
	for _, s := range t.secrets {
		desc := s.desc + " Write-only: never stored in state. Sent on create, and on update only when `" + s.name + "_wo_version` changes."
		if s.isMap {
			attrs[s.name+"_wo"] = schema.MapAttribute{ElementType: types.StringType, Optional: true, WriteOnly: true, Sensitive: true, MarkdownDescription: desc}
		} else {
			attrs[s.name+"_wo"] = schema.StringAttribute{Optional: true, WriteOnly: true, Sensitive: true, MarkdownDescription: desc}
		}
		attrs[s.name+"_wo_version"] = schema.Int64Attribute{Optional: true,
			MarkdownDescription: "Change this number to send a new `" + s.name + "_wo` value, or to clear the secret when `" + s.name + "_wo` is removed."}
	}
	return schema.SingleNestedBlock{
		MarkdownDescription: t.desc + " Changing the check type replaces the check.",
		Attributes:          attrs,
		PlanModifiers: []planmodifier.Object{objectplanmodifier.RequiresReplaceIf(
			func(_ context.Context, req planmodifier.ObjectRequest, resp *objectplanmodifier.RequiresReplaceIfFuncResponse) {
				resp.RequiresReplace = req.StateValue.IsNull() != req.PlanValue.IsNull()
			},
			"Changing the check type replaces the check.", "Changing the check type replaces the check.")},
	}
}

func checkResourceSchema() schema.Schema {
	attrs := map[string]schema.Attribute{
		"id": schema.StringAttribute{Computed: true, MarkdownDescription: "Check UUID, generated by the provider on create.",
			PlanModifiers: []planmodifier.String{stringplanmodifier.UseStateForUnknown()}},
		enabledAttr: schema.BoolAttribute{Optional: true, Computed: true, Default: booldefault.StaticBool(true),
			MarkdownDescription: "Whether the check runs. Defaults to `true`. Project and group settings can still disable it."},
		connectionIDAttr: schema.StringAttribute{Optional: true, MarkdownDescription: connectionIDDesc,
			Validators: []validator.String{uuidCheck{}}},
	}
	for _, f := range commonCheckFields {
		attrs[f.name] = f.resourceAttribute()
	}
	blocks := make(map[string]schema.Block, len(checkTypes))
	for _, t := range checkTypes {
		blocks[t.block] = t.resourceBlock()
	}
	return schema.Schema{
		MarkdownDescription: "Manages an Ensafely Check. Exactly one type block (" + checkTypeBlockList() + ") is required; " +
			"changing the type replaces the check. Inheritable settings left null use the Tenant's check defaults, " +
			"so changing `ensafely_check_defaults` causes no diff here. Import with the check UUID.",
		Attributes: attrs,
		Blocks:     blocks,
	}
}

var connectionIDDesc = "ID of an `ensafely_connection` that supplies host, port and credentials, instead of inline credentials. " +
	"Supported by " + connectionTypeList() + ". Setting it together with an inline credential " +
	"(user name, password, basic-auth or `uri_wo`) is an error, and inline credential secrets stored earlier are cleared."

// connectionTypeList describes which type blocks accept connection_id.
func connectionTypeList() string {
	var parts []string
	for _, t := range checkTypes {
		if t.connection != "" {
			parts = append(parts, fmt.Sprintf("`%s` (a `%s` Connection)", t.block, t.connection))
		}
	}
	return strings.Join(parts, ", ")
}

// Data source schema: the same fields, computed, without write-only secrets.

func (f checkField) dataSourceAttribute() dsschema.Attribute {
	switch f.kind {
	case kindInt:
		return dsschema.Int64Attribute{Computed: true, MarkdownDescription: f.desc}
	case kindBool:
		return dsschema.BoolAttribute{Computed: true, MarkdownDescription: f.desc}
	case kindIntSet:
		return dsschema.SetAttribute{ElementType: types.Int64Type, Computed: true, MarkdownDescription: f.desc}
	case kindStringSet:
		return dsschema.SetAttribute{ElementType: types.StringType, Computed: true, MarkdownDescription: f.desc}
	default:
		return dsschema.StringAttribute{Computed: true, MarkdownDescription: f.desc}
	}
}

func checkDataSourceSchema() dsschema.Schema {
	attrs := map[string]dsschema.Attribute{
		"id":        dsschema.StringAttribute{Required: true, MarkdownDescription: "Check UUID."},
		"type":      dsschema.StringAttribute{Computed: true, MarkdownDescription: "API check type. Type attributes are filled only for types this provider manages (" + checkTypeBlockList() + ")."},
		enabledAttr: dsschema.BoolAttribute{Computed: true, MarkdownDescription: "Whether the check runs."},
		connectionIDAttr: dsschema.StringAttribute{Computed: true,
			MarkdownDescription: "ID of the `ensafely_connection` the check uses, or null for inline credentials."},
	}
	for _, f := range commonCheckFields {
		attrs[f.name] = f.dataSourceAttribute()
	}
	for _, t := range checkTypes {
		nested := make(map[string]dsschema.Attribute, len(t.fields))
		for _, f := range t.fields {
			nested[f.name] = f.dataSourceAttribute()
		}
		attrs[t.block] = dsschema.SingleNestedAttribute{Computed: true, Attributes: nested,
			MarkdownDescription: t.desc + " Null unless the check has this type. Secrets are not readable."}
	}
	return dsschema.Schema{
		MarkdownDescription: "Reads an Ensafely Check by UUID. Inheritable settings that the check leaves to the Tenant's check defaults are null.",
		Attributes:          attrs,
	}
}

// validateCheckConfig enforces exactly one type block, the required fields
// of the active block, the connection_id rules (#115) and rejects URLs that
// carry a password (the API masks it on read, which would cause drift).
//
// An unknown connection_id may still be set, so it relaxes the fields a
// Connection supplies but raises no conflict.
func validateCheckConfig(connectionID types.String, blocks map[string]types.Object, diags *diag.Diagnostics) {
	var set []string
	unknown := false
	for _, t := range checkTypes {
		obj := blocks[t.block]
		if obj.IsUnknown() {
			unknown = true
		} else if !obj.IsNull() {
			set = append(set, t.block)
		}
	}
	if len(set) > 1 {
		diags.AddError("Conflicting check type blocks",
			fmt.Sprintf("Exactly one check type block is allowed; found %s.", strings.Join(set, ", ")))
	}
	if len(set) == 0 && !unknown {
		diags.AddError("Missing check type block", "Exactly one check type block ("+checkTypeBlockList()+") is required.")
	}
	connSet := !connectionID.IsNull() && !connectionID.IsUnknown()
	connMaybe := !connectionID.IsNull()
	for _, t := range checkTypes {
		obj := blocks[t.block]
		if obj.IsNull() || obj.IsUnknown() {
			continue
		}
		if connSet && t.connection == "" {
			diags.AddAttributeError(path.Root(connectionIDAttr), "Connection not supported",
				fmt.Sprintf("A %s check cannot use connection_id. Supported: %s.", t.block, connectionTypeList()))
		}
		attrs := obj.Attributes()
		for _, f := range t.fields {
			v := attrs[f.name]
			isNull := v == nil || v.IsNull()
			if f.required && isNull && !(f.fromConnection && connMaybe && t.connection != "") {
				diags.AddAttributeError(path.Root(t.block).AtName(f.name), "Missing required argument",
					fmt.Sprintf("The argument %q is required in a %s block%s.", f.name, t.block, unlessConnection(f.fromConnection)))
			}
			if f.credential && connSet && !isNull {
				conflictsWithConnection(path.Root(t.block).AtName(f.name), diags)
			}
			if f.url && !isNull && !v.IsUnknown() {
				if parsed, err := url.Parse(v.(types.String).ValueString()); err == nil && parsed.User != nil {
					if _, hasPassword := parsed.User.Password(); hasPassword {
						diags.AddAttributeError(path.Root(t.block).AtName(f.name), "Password in URL",
							"Remove the password from the URL: the API masks it on read."+urlPasswordHint(t))
					}
				}
			}
		}
		for _, sec := range t.secrets {
			v := attrs[sec.name+"_wo"]
			isNull := v == nil || v.IsNull()
			if sec.required && isNull && !connMaybe {
				diags.AddAttributeError(path.Root(t.block).AtName(sec.name+"_wo"), "Missing required argument",
					fmt.Sprintf("The argument %q is required in a %s block%s.", sec.name+"_wo", t.block, unlessConnection(t.connection != "")))
			}
			if sec.credential && connSet && !isNull {
				conflictsWithConnection(path.Root(t.block).AtName(sec.name+"_wo"), diags)
			}
		}
	}
}

func unlessConnection(applies bool) string {
	if applies {
		return " unless connection_id is set"
	}
	return ""
}

func urlPasswordHint(t checkType) string {
	if t.block == "http" {
		return " Use basic_auth_user and basic_auth_password_wo instead."
	}
	return ""
}

func conflictsWithConnection(p path.Path, diags *diag.Diagnostics) {
	diags.AddAttributeError(p, "Conflicting credentials",
		"connection_id supplies the credentials; remove this inline credential or connection_id.")
}

// Validators. Zero values are rejected because the API stores them as
// "unset" (see checkField).

type stringCheck struct {
	duration bool
	oneOf    []string
}

func (v stringCheck) Description(context.Context) string {
	switch {
	case len(v.oneOf) > 0:
		return "one of " + strings.Join(v.oneOf, ", ")
	case v.duration:
		return "a nonempty Go duration"
	}
	return "a nonempty string"
}
func (v stringCheck) MarkdownDescription(ctx context.Context) string { return v.Description(ctx) }

func (v stringCheck) ValidateString(_ context.Context, req validator.StringRequest, resp *validator.StringResponse) {
	if req.ConfigValue.IsNull() || req.ConfigValue.IsUnknown() {
		return
	}
	s := req.ConfigValue.ValueString()
	switch {
	case s == "":
		resp.Diagnostics.AddAttributeError(req.Path, "Empty value", "Omit the attribute (or set null) instead of an empty string.")
	case len(v.oneOf) > 0 && !slices.Contains(v.oneOf, s):
		resp.Diagnostics.AddAttributeError(req.Path, "Invalid value", fmt.Sprintf("%q is not one of %s.", s, strings.Join(v.oneOf, ", ")))
	case v.duration:
		if d, err := time.ParseDuration(s); err != nil || d <= 0 {
			resp.Diagnostics.AddAttributeError(req.Path, "Invalid duration", fmt.Sprintf("%q is not a positive Go duration such as 30s, 5m or 1h.", s))
		}
	}
}

// uuidCheck accepts a UUID, the form of every Connection ID.
type uuidCheck struct{}

func (uuidCheck) Description(context.Context) string               { return "a UUID" }
func (v uuidCheck) MarkdownDescription(ctx context.Context) string { return v.Description(ctx) }

func (uuidCheck) ValidateString(_ context.Context, req validator.StringRequest, resp *validator.StringResponse) {
	if req.ConfigValue.IsNull() || req.ConfigValue.IsUnknown() {
		return
	}
	if !isUUID(req.ConfigValue.ValueString()) {
		resp.Diagnostics.AddAttributeError(req.Path, "Invalid connection ID",
			fmt.Sprintf("%q is not a UUID; use the id of an ensafely_connection.", req.ConfigValue.ValueString()))
	}
}

type int64Range struct{ min, max int64 }

func (v int64Range) Description(context.Context) string {
	if v.max > 0 {
		return fmt.Sprintf("between %d and %d", v.min, v.max)
	}
	return fmt.Sprintf("at least %d", v.min)
}
func (v int64Range) MarkdownDescription(ctx context.Context) string { return v.Description(ctx) }

func (v int64Range) ValidateInt64(ctx context.Context, req validator.Int64Request, resp *validator.Int64Response) {
	if req.ConfigValue.IsNull() || req.ConfigValue.IsUnknown() {
		return
	}
	if n := req.ConfigValue.ValueInt64(); n < v.min || (v.max > 0 && n > v.max) {
		resp.Diagnostics.AddAttributeError(req.Path, "Value out of range", fmt.Sprintf("Must be %s, got %d.", v.Description(ctx), n))
	}
}

type setCheck struct{ elemMin, elemMax int64 }

func (v setCheck) Description(context.Context) string {
	return "a nonempty set of nonempty values"
}
func (v setCheck) MarkdownDescription(ctx context.Context) string { return v.Description(ctx) }

func (v setCheck) ValidateSet(_ context.Context, req validator.SetRequest, resp *validator.SetResponse) {
	if req.ConfigValue.IsNull() || req.ConfigValue.IsUnknown() {
		return
	}
	elems := req.ConfigValue.Elements()
	if len(elems) == 0 {
		resp.Diagnostics.AddAttributeError(req.Path, "Empty set", "Omit the attribute (or set null) instead of an empty set.")
		return
	}
	for _, e := range elems {
		checkSetElement(e, v, req.Path, &resp.Diagnostics)
	}
}

func checkSetElement(e attr.Value, v setCheck, p path.Path, diags *diag.Diagnostics) {
	switch e := e.(type) {
	case types.String:
		if !e.IsUnknown() && e.ValueString() == "" {
			diags.AddAttributeError(p, "Empty value", "Set elements must be nonempty.")
		}
	case types.Int64:
		if e.IsUnknown() || v.elemMax == 0 {
			return
		}
		if n := e.ValueInt64(); n < v.elemMin || n > v.elemMax {
			diags.AddAttributeError(p, "Value out of range", fmt.Sprintf("Elements must be between %d and %d, got %d.", v.elemMin, v.elemMax, n))
		}
	}
}
